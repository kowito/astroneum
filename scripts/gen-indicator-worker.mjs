#!/usr/bin/env node
// Bundles src/engine/workers/indicatorWorker.entry.ts (and the kernels it imports)
// into a string module that IndicatorWorkerPool starts from a Blob URL. Generating
// it from the same TypeScript the main thread runs keeps worker and main-thread
// results identical; the unit tests fail if the committed output is stale.
//
//   pnpm gen:worker

import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = 'src/engine/workers/indicatorWorker.entry.ts'
export const OUTPUT = 'src/engine/workers/indicatorWorkerSource.generated.ts'

export async function generate () {
  const { build } = createRequire(path.join(root, 'package.json'))('esbuild')
  const result = await build({
    absWorkingDir: root,
    entryPoints: [ENTRY],
    bundle: true,
    format: 'iife',
    minify: true,
    target: 'es2020',
    legalComments: 'none',
    write: false
  })
  const code = result.outputFiles[0].text.trim()
  return '// Generated by scripts/gen-indicator-worker.mjs from indicatorWorker.entry.ts — do not edit.\n' +
    '// Run `pnpm gen:worker` after changing the worker entry or TypedArrayIndicators.ts.\n' +
    `export default ${JSON.stringify(code)}\n`
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, OUTPUT), await generate())
  console.log(`wrote ${OUTPUT}`)
}
